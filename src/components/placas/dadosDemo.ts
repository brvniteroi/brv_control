const AGORA = new Date();
const ANO_ATUAL = AGORA.getFullYear();
const MES_ATUAL = AGORA.getMonth();

function diasAtrasIso(dias: number, hora = 10): string {
  const d = new Date(AGORA.getTime() - dias * 86_400_000);
  d.setHours(hora, 15, 0, 0);
  return d.toISOString();
}

function dataNoAnoIso(mesOffsetNegativo: number, dia: number, hora = 14): string {
  const mesAlvo = Math.max(0, MES_ATUAL - mesOffsetNegativo);
  const d = new Date(ANO_ATUAL, mesAlvo, Math.min(27, Math.max(1, dia)), hora, 30, 0);
  return d.toISOString();
}

