function criarItemCat(
  p: Omit<
    CatalogItem,
    'created_at' | 'updated_at' | 'origin' | 'taxable_unit' | 'invoice_description'
  > & {
    origin?: 0 | 1 | 2;
    taxable_unit?: string | null;
    invoice_description?: string | null;
  },
): CatalogItem {
  return {
    ...p,
    origin: p.origin ?? 0,
    taxable_unit: p.taxable_unit ?? p.unit,
    invoice_description: p.invoice_description ?? null,
    created_at: '2026-10-01T10:00:00.000Z',
    updated_at: '2026-11-20T14:00:00.000Z',
  };
}

