function montarVendaDemo(p: {
  idx: number;
  number: string;
  status?: Sale['status'];
  originType: Sale['origin_type'];
  quoteId?: string | null;
  quoteNumber?: string | null;
  osId?: string | null;
  osNumber?: number | null;
  cliIdx: number | null;
  invoiceDoc?: string | null;
  sellerIdx: number;
  createdAt: string;
  discountCents?: number;
  cancelReason?: string | null;
  linhas: LinhaOrcSeed[];
  pagamentos: Array<{
    method: Sale['payments'][number]['method'];
    amountCents: number;
    tenderedCents?: number | null;
    changeCents?: number;
    accountId?: string | null;
    accountName?: string | null;
    machineId?: string | null;
    machineName?: string | null;
    installments?: number;
    feePct?: number | null;
  }>;
  notaProdutosStatus?: 'nao_emitida' | 'emitida' | 'erro' | 'cancelada';
  notaProdutosModel?: 'nfce' | 'nfe';
  notaProdutosErro?: string | null;
  notaServicosStatus?: 'nao_emitida' | 'emitida' | 'erro' | 'cancelada';
  notaServicosErro?: string | null;
}): Sale {
  const id = `vnd-demo-${p.idx}`;
  const cli = p.cliIdx !== null ? CLIENTES_DEMO_VENDAS[p.cliIdx] : null;
  const end = cli?.addresses[0] ?? null;
  const vend = VENDEDORES_DEMO[p.sellerIdx] ?? VENDEDORES_DEMO[0];

  let prodSub = 0;
  let servSub = 0;
  const items = p.linhas.map((l, i) => {
    const bruto = Math.round(l.qty * l.unitCents);
    const disc = l.discCents ?? 0;
    const total = Math.max(0, bruto - disc);
    if (l.kind === 'produto') prodSub += total;
    else servSub += total;
    return {
      id: `${id}-item-${i + 1}`,
      sale_id: id,
      catalog_item_id: l.catId,
      is_custom: l.catId === null,
      kind: l.kind,
      code: l.code,
      name: l.name,
      unit: l.unit,
      quantity: l.qty,
      unit_price_cents: l.unitCents,
      discount_mode: 'valor' as const,
      discount_input: disc,
      discount_cents: disc,
      total_cents: total,
      sort_order: i + 1,
    };
  });

  const descGeral = p.discountCents ?? 0;
  const totalCents = Math.max(0, prodSub + servSub - descGeral);

  let paidCents = 0;
  let changeCents = 0;
  const payments = p.pagamentos.map((pg, i) => {
    paidCents += pg.amountCents;
    changeCents += pg.changeCents ?? 0;
    const feePct = pg.feePct ?? null;
    const feeCents = feePct ? Math.round((pg.amountCents * feePct) / 100) : null;
    return {
      id: `${id}-pag-${i + 1}`,
      sale_id: id,
      method: pg.method,
      amount_cents: pg.amountCents,
      tendered_cents: pg.tenderedCents ?? null,
      change_cents: pg.changeCents ?? 0,
      account_id: pg.accountId ?? 'conta-itau',
      account_name: pg.accountName ?? 'Itaú Empresas',
      card_machine_id: pg.machineId ?? null,
      card_machine_name: pg.machineName ?? null,
      installments: pg.installments ?? 1,
      estimated_fee_percent: feePct,
      estimated_fee_cents: feeCents,
      paid_at: p.createdAt,
      created_by_name: vend.name,
      notes: null,
    };
  });

  const documents: Sale['documents'] = [];
  if (prodSub > 0) {
    const st = p.notaProdutosStatus ?? 'nao_emitida';
    const mod = p.notaProdutosModel ?? (cli?.person_type === 'PJ' ? 'nfe' : 'nfce');
    documents.push({
      id: `${id}-doc-prod`,
      sale_id: id,
      group: 'produtos',
      model: mod,
      status: st,
      amount_cents: prodSub,
      number: st === 'emitida' || st === 'cancelada' ? String(10400 + p.idx) : null,
      series: st === 'emitida' || st === 'cancelada' ? '1' : null,
      access_key:
        st === 'emitida' || st === 'cancelada'
          ? `33261107320361000164650010000104${String(p.idx).padStart(2, '0')}1000000019`
          : null,
      xml_url: st === 'emitida' ? `#xml-demo-${id}-prod` : null,
      pdf_url: st === 'emitida' ? `#pdf-demo-${id}-prod` : null,
      error_message: st === 'erro' ? (p.notaProdutosErro ?? 'Rejeição 778: Informado NCM inexistente na tabela vigente da SEFAZ.') : null,
      cancel_reason: st === 'cancelada' ? 'Cancelada a pedido do cliente' : null,
      issued_at: st === 'emitida' ? p.createdAt : null,
      cancelled_at: st === 'cancelada' ? p.createdAt : null,
    });
  }
  if (servSub > 0) {
    const st = p.notaServicosStatus ?? 'nao_emitida';
    documents.push({
      id: `${id}-doc-serv`,
      sale_id: id,
      group: 'servicos',
      model: 'nfse',
      status: st,
      amount_cents: servSub,
      number: st === 'emitida' || st === 'cancelada' ? `2026000${180 + p.idx}` : null,
      series: st === 'emitida' || st === 'cancelada' ? 'ADN' : null,
      access_key:
        st === 'emitida' || st === 'cancelada'
          ? `3303302220732036100016420261124000${180 + p.idx}`
          : null,
      xml_url: st === 'emitida' ? `#xml-demo-${id}-serv` : null,
      pdf_url: st === 'emitida' ? `#pdf-demo-${id}-serv` : null,
      error_message: st === 'erro' ? (p.notaServicosErro ?? 'Falha de comunicação com o webservice do Emissor Nacional.') : null,
      cancel_reason: st === 'cancelada' ? 'Substituição de nota' : null,
      issued_at: st === 'emitida' ? p.createdAt : null,
      cancelled_at: st === 'cancelada' ? p.createdAt : null,
    });
  }

  return {
    id,
    number: p.number,
    status: p.status ?? 'ativa',
    origin_type: p.originType,
    quote_id: p.quoteId ?? null,
    quote_number: p.quoteNumber ?? null,
    service_order_id: p.osId ?? null,
    service_order_number: p.osNumber ?? null,
    customer_id: cli?.id ?? null,
    customer_name: cli?.name ?? 'Consumidor final',
    customer_person_type: cli?.person_type ?? 'PF',
    customer_document: cli?.document ?? null,
    invoice_document: p.invoiceDoc ?? cli?.document ?? null,
    address_id: end?.id ?? null,
    address_text: end?.text ?? null,
    seller_id: vend.id,
    seller_name: vend.name,
    products_subtotal_cents: prodSub,
    services_subtotal_cents: servSub,
    general_discount_cents: descGeral,
    total_cents: totalCents,
    paid_cents: paidCents,
    change_cents: changeCents,
    notes: null,
    cancel_reason: p.cancelReason ?? null,
    cancelled_at: p.status === 'cancelada' ? p.createdAt : null,
    cancelled_by_name: p.status === 'cancelada' ? 'Adriana Lobo' : null,
    items,
    payments,
    documents,
    events: [
      {
        id: `${id}-ev-1`,
        sale_id: id,
        description: `Venda ${p.number} registrada (${p.originType === 'balcao' ? 'Balcão' : p.originType === 'orcamento' ? `Orçamento ${p.quoteNumber}` : `OS ${p.osNumber}`}).`,
        actor_name: vend.name,
        created_at: p.createdAt,
      },
    ],
    created_at: p.createdAt,
    updated_at: p.createdAt,
  };
}

