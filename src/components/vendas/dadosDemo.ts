interface LinhaOrcSeed {
  catId: string | null;
  code: string;
  name: string;
  kind: 'produto' | 'servico';
  unit: string;
  qty: number;
  unitCents: number;
  discCents?: number;
}

function montarOrcamentoDemo(p: {
  idx: number;
  number: string;
  status: Quote['status'];
  cliIdx: number | null; // null = Consumidor final, 0..2 = CLIENTES_DEMO_VENDAS
  contactName: string | null;
  sellerIdx: number;
  createdAt: string;
  validUntil: string;
  validityDays?: number;
  generalDiscountCents?: number;
  freightCents?: number;
  paymentTerms?: string | null;
  notes?: string | null;
  internalNotes?: string | null;
  sentAt?: string | null;
  respondedAt?: string | null;
  channel?: Quote['response_channel'];
  respondedBy?: string | null;
  responseNote?: string | null;
  saleId?: string | null;
  saleNumber?: string | null;
  osId?: string | null;
  osNumber?: number | null;
  linhas: LinhaOrcSeed[];
}): Quote {
  const id = `orc-demo-${p.idx}`;
  const cli = p.cliIdx !== null ? CLIENTES_DEMO_VENDAS[p.cliIdx] : null;
  const end = cli?.addresses[0] ?? null;
  const vend = VENDEDORES_DEMO[p.sellerIdx] ?? VENDEDORES_DEMO[0];

  let prodSub = 0;
  let servSub = 0;
  const items = p.linhas.map((l, i) => {
    const bruto = Math.round(l.qty * l.unitCents);
    const disc = l.discCents ?? 0;
    const total = Math.max(0, bruto - disc);
    if (l.kind === 'produto') prodSub += total;
    else servSub += total;
    return {
      id: `${id}-item-${i + 1}`,
      quote_id: id,
      catalog_item_id: l.catId,
      is_custom: l.catId === null,
      kind: l.kind,
      code: l.code,
      name: l.name,
      unit: l.unit,
      quantity: l.qty,
      unit_price_cents: l.unitCents,
      discount_mode: 'valor' as const,
      discount_input: disc,
      discount_cents: disc,
      total_cents: total,
      sort_order: i + 1,
    };
  });

  const descGeral = p.generalDiscountCents ?? 0;
  const frete = p.freightCents ?? 0;
  const totalCents = Math.max(0, prodSub + servSub - descGeral + frete);

  return {
    id,
    number: p.number,
    status: p.status,
    customer_id: cli?.id ?? null,
    customer_name: cli?.name ?? 'Consumidor final',
    customer_person_type: cli?.person_type ?? 'PF',
    customer_document: cli?.document ?? null,
    address_id: end?.id ?? null,
    address_text: end?.text ?? null,
    contact_name: p.contactName,
    contact_phone: cli?.phone ?? '(21) 99911-0000',
    seller_id: vend.id,
    seller_name: vend.name,
    validity_days: p.validityDays ?? 10,
    valid_until: p.validUntil,
    products_subtotal_cents: prodSub,
    services_subtotal_cents: servSub,
    general_discount_cents: descGeral,
    freight_cents: frete,
    total_cents: totalCents,
    payment_terms_note: p.paymentTerms ?? 'PIX à vista ou cartão de crédito em até 6x',
    notes:
      p.notes ??
      `${OBSERVACOES_PADRAO_ORCAMENTO_INICIAIS[0].texto}\n${OBSERVACOES_PADRAO_ORCAMENTO_INICIAIS[1].texto}`,
    internal_notes: p.internalNotes ?? null,
    public_token: `demo-orc-${p.idx}`,
    sent_at: p.sentAt ?? null,
    responded_at: p.respondedAt ?? null,
    response_channel: p.channel ?? null,
    responded_by_name: p.respondedBy ?? null,
    response_note: p.responseNote ?? null,
    converted_sale_id: p.saleId ?? null,
    converted_sale_number: p.saleNumber ?? null,
    converted_service_order_id: p.osId ?? null,
    converted_service_order_number: p.osNumber ?? null,
    items,
    created_at: p.createdAt,
    updated_at: p.respondedAt ?? p.sentAt ?? p.createdAt,
  };
}

